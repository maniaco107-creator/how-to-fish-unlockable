function generateAllSkins() {
    for (const itemID in SKINS) {
        const item = SKINS[itemID];

        const common = document.getElementById(`${item.folder}-common`);
        const rare = document.getElementById(`${item.folder}-rare`);
        const legendary = document.getElementById(`${item.folder}-legendary`);

        item.skins.forEach(skin => {
            const wrapper = document.createElement("div");
            wrapper.classList.add("skin");

            const img = document.createElement("img");
            img.src = `images/${item.folder}/${skin.name}.png`;
            img.dataset.skinId = skin.id;
            img.dataset.itemId = itemID;

            const label = document.createElement("div");
            label.classList.add("skin-name", skin.rarity);
            label.textContent = skin.name;

            wrapper.appendChild(img);
            wrapper.appendChild(label);

            if (skin.rarity === "common") common.appendChild(wrapper);
            else if (skin.rarity === "rare") rare.appendChild(wrapper);
            else legendary.appendChild(wrapper);
        });
    }
}

document.querySelectorAll(".category-title").forEach(title => {
    title.addEventListener("click", () => {
        const category = title.closest(".category");
        category.classList.toggle("collapsed");
    });
});

function applyUnlockedSkins(data) {
    const unlocked = data.UnlockedItemSkins || [];

    unlocked.forEach(entry => {
        const itemID = entry.ID;
        const skins = entry.SkinsUnlocked;

        skins.forEach(skinNumber => {
            const img = document.querySelector(
                `img[data-item-id="${itemID}"][data-skin-id="${skinNumber}"]`
            );
            if (img) img.classList.add("unlocked");
        });
    });

    // Boat skins (special case)
    if (data.UnlockedBoatSkins) {
        data.UnlockedBoatSkins.forEach(skinNumber => {
            const img = document.querySelector(
                `img[data-item-id="boats"][data-skin-id="${skinNumber}"]`
            );
            if (img) img.classList.add("unlocked");
        });
    }
}



function loadSaveFile(file) {
    const reader = new FileReader();

    reader.onload = () => {
        const data = JSON.parse(reader.result);
        applyUnlockedSkins(data);
    };

    reader.readAsText(file);
}

const dropzone = document.getElementById("dropzone");

// Empêche le navigateur d'ouvrir le fichier
["dragenter", "dragover", "dragleave", "drop"].forEach(eventName => {
    dropzone.addEventListener(eventName, e => {
        e.preventDefault();
        e.stopPropagation();
    });
});

dropzone.addEventListener("dragover", () => {
    dropzone.style.background = "#b4d9ff";
});

dropzone.addEventListener("dragleave", () => {
    dropzone.style.background = "#e3f2ff";
});

dropzone.addEventListener("drop", e => {
    dropzone.style.background = "#e3f2ff";

    const file = e.dataTransfer.files[0];
    if (!file) return;

    loadSaveFile(file); // ta fonction optimisée
});

